/** Put content/actions before presentation, across props, slots and events. */
export function standardParameterOrder(
  name: keyof typeof STANDARD_ARGUMENT_PREFIXES,
  definition: GenerativeUIComponentDeclaration,
): string[] {
  const keys = [
    ...Object.keys(
      definition.props ? (toJsonSchema(definition.props).properties ?? {}) : {},
    ),
    ...Object.keys(definition.slots ?? {}),
    ...Object.keys(definition.events ?? {}),
  ];
  const prefix: readonly string[] = STANDARD_ARGUMENT_PREFIXES[name];
  const remainder = keys.filter((key) => !prefix.includes(key));
  // Keep unknown prefix keys: createGenerativeUI rejects them, catching a
  // renamed property whose calling convention was not updated.
  return [
    ...prefix,
    ...remainder.filter((key) => !PRESENTATION_PARAMETERS.has(key)),
    ...remainder.filter((key) => PRESENTATION_PARAMETERS.has(key)),
  ];
}
