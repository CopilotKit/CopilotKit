// Generates src/styles/stylesheet.ts: every file in src/styles/css, minified
// into one string. Each framework package injects this string, so apps get
// styled UI without importing a stylesheet, and the CSS ships with no runtime
// dependency. With `--css <file>` it also writes the same CSS as a file, the
// `@copilotkit/core/styles.css` that apps can import to have browsers cache it.
//
// How the CSS meets the app's CSS:
// - theme.css loads in Tailwind v4's `base` cascade layer. An app that sets
//   `[data-copilotkit] { --primary: ... }` in any layer, or in no layer, wins.
// - base.css, a reset scoped to [data-copilotkit], loads in the `components`
//   layer. It beats Tailwind's preflight, and a Tailwind class on an element
//   the app renders inside the chat beats it.
// - The component rules are outside cascade layers, with the specificity of
//   two element selectors (`html body`). A global reset outside a layer, such
//   as `* { padding: 0 }` or `button { border-radius: 0 }`, loses to them, as
//   do Tailwind v3's preflight and Bootstrap's reboot. Any class rule of the
//   app wins. A Tailwind v4 utility is in a layer, so on a CopilotKit element
//   it needs `!` (`p-4!`).
//
// The source files write each selector in `:where()`, so every component rule
// has the same specificity, and when two files style the same element the
// later one wins. Files load in this order, so a parent overrides the parts it
// renders:
//   1. ui/        primitives (button, tooltip, ...)
//   2. *.css      chat components
//   3. layout/    containers that render the components (chat view, popup, ...)
// Within a group, files load in name order.
//
// Run: node scripts/generate-stylesheet.mjs [--check] [--css <file>]
// The generated file is committed; `--check` fails when it is out of date.
import { transform } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const cssDir = path.join(packageDir, "src/styles/css");
const outputFile = path.join(packageDir, "src/styles/stylesheet.ts");

const cssFilesIn = (dir) =>
  fs.existsSync(path.join(cssDir, dir))
    ? fs
        .readdirSync(path.join(cssDir, dir))
        .filter((name) => name.endsWith(".css"))
        .sort()
        .map((name) => path.join(dir, name))
    : [];
const read = (name) => fs.readFileSync(path.join(cssDir, name), "utf8");
const order = [
  ...cssFilesIn("ui"),
  ...cssFilesIn(".").filter(
    (name) => !["base.css", "theme.css"].includes(name),
  ),
  ...cssFilesIn("layout"),
];
/**
 * Splits minified CSS into its `@keyframes` blocks and every other top-level
 * rule. A `@keyframes` rule cannot nest in a style rule.
 */
function splitKeyframes(css) {
  const keyframes = [];
  const rules = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < css.length; i++) {
    if (css[i] === "{") depth++;
    if (css[i] !== "}" || --depth !== 0) continue;
    const block = css.slice(start, i + 1);
    (block.startsWith("@keyframes") ? keyframes : rules).push(block);
    start = i + 1;
  }
  return { keyframes: keyframes.join(""), rules: rules.join("") };
}

const minify = async (source, options) =>
  (await transform(source, { loader: "css", minify: true, ...options })).code;

const { keyframes, rules } = splitKeyframes(
  await minify(order.map(read).join("\n")),
);
// Declaring the layer order first keeps `base` before `utilities` when this
// stylesheet loads before an app's Tailwind CSS. Nesting the rules in
// `html body` gives each selector the specificity of two element selectors,
// and `nesting: false` writes `html body` into every selector.
const css = await minify(
  `@layer theme, base, components, utilities;
@layer base {
${read("theme.css")}
}
@layer components {
${read("base.css")}
}
html body {
${rules}
}
${keyframes}`,
  { supported: { nesting: false } },
);

const output = `// Generated by scripts/generate-stylesheet.mjs from src/styles/css. Do not edit.
export const stylesheet: string = ${JSON.stringify(css.trim())};
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputFile)
    ? fs.readFileSync(outputFile, "utf8")
    : "";
  if (current !== output) {
    console.error(
      "src/styles/stylesheet.ts is out of date. Run: node scripts/generate-stylesheet.mjs",
    );
    process.exit(1);
  }
} else {
  fs.writeFileSync(outputFile, output);
}

const cssFlag = process.argv.indexOf("--css");
if (cssFlag !== -1) {
  const cssFile = path.resolve(process.argv[cssFlag + 1]);
  fs.mkdirSync(path.dirname(cssFile), { recursive: true });
  fs.writeFileSync(cssFile, `${css.trim()}\n`);
}
