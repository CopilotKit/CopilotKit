// Generates src/styles/stylesheet.ts: every file in src/styles/css, minified
// into one string. Each framework package injects this string, so apps get
// styled UI without importing a stylesheet, and the CSS ships with no runtime
// dependency. With `--css <file>` it also writes the same CSS as a file, the
// `@copilotkit/core/styles.css` that apps can import to have browsers cache it.
//
// The CSS uses Tailwind v4's cascade layers, as the Tailwind build it replaces
// did. theme.css loads in `base`, everything else in `utilities`. So the app's
// own CSS wins: unlayered rules beat every layer, and a Tailwind utility such
// as `p-4` beats a zero-specificity rule in the same layer. Our rules also beat
// a reset in the app's `base` layer, such as Tailwind's preflight.
//
// Every rule has zero specificity, so when two files style the same element
// the later one wins. Files load in this order, so a parent overrides the
// parts it renders:
//   1. base.css   reset, base element styles, shared keyframes
//   2. ui/        primitives (button, tooltip, ...)
//   3. *.css      chat components
//   4. layout/    containers that render the components (chat view, popup, ...)
// Within a group, files load in name order.
//
// Run: node scripts/generate-stylesheet.mjs [--check] [--css <file>]
// The generated file is committed; `--check` fails when it is out of date.
import { transform } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const cssDir = path.join(packageDir, "src/styles/css");
const outputFile = path.join(packageDir, "src/styles/stylesheet.ts");

const cssFilesIn = (dir) =>
  fs.existsSync(path.join(cssDir, dir))
    ? fs
        .readdirSync(path.join(cssDir, dir))
        .filter((name) => name.endsWith(".css"))
        .sort()
        .map((name) => path.join(dir, name))
    : [];
const read = (name) => fs.readFileSync(path.join(cssDir, name), "utf8");
const order = [
  "base.css",
  ...cssFilesIn("ui"),
  ...cssFilesIn(".").filter(
    (name) => !["base.css", "theme.css"].includes(name),
  ),
  ...cssFilesIn("layout"),
];
// Declaring the order first keeps `base` before `utilities` when this
// stylesheet loads before the app's.
const source = `@layer theme, base, components, utilities;
@layer base {
${read("theme.css")}
}
@layer utilities {
${order.map(read).join("\n")}
}`;

const { code: css } = await transform(source, { loader: "css", minify: true });

const output = `// Generated by scripts/generate-stylesheet.mjs from src/styles/css. Do not edit.
export const stylesheet: string = ${JSON.stringify(css.trim())};
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputFile)
    ? fs.readFileSync(outputFile, "utf8")
    : "";
  if (current !== output) {
    console.error(
      "src/styles/stylesheet.ts is out of date. Run: node scripts/generate-stylesheet.mjs",
    );
    process.exit(1);
  }
} else {
  fs.writeFileSync(outputFile, output);
}

const cssFlag = process.argv.indexOf("--css");
if (cssFlag !== -1) {
  const cssFile = path.resolve(process.argv[cssFlag + 1]);
  fs.mkdirSync(path.dirname(cssFile), { recursive: true });
  fs.writeFileSync(cssFile, `${css.trim()}\n`);
}
