// Writes the QuickJS WebAssembly into a TypeScript module as base64, so the
// skill-script sandbox loads it without reading a .wasm file. A bundled server
// (Next.js with webpack or Turbopack, a standalone output, Vercel) may not ship
// or find that file. Run it after a QuickJS version change:
//   pnpm --filter @copilotkit/runtime generate-quickjs-wasm
// A test fails when the embedded bytes differ from the installed package.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const wasm = readFileSync(
  require.resolve("@jitl/quickjs-wasmfile-release-sync/wasm"),
);
const out = path.resolve(
  import.meta.dirname,
  "../src/v2/runtime/intelligence-platform/skill-registry/quickjs-wasm.generated.ts",
);
writeFileSync(
  out,
  "// Generated by scripts/generate-quickjs-wasm.mjs. Do not edit.\n" +
    "// The WebAssembly of @jitl/quickjs-wasmfile-release-sync, as base64.\n" +
    `export const QUICKJS_WASM_BASE64 =\n  "${wasm.toString("base64")}";\n`,
);
console.log(`Wrote ${wasm.length} bytes of WebAssembly to ${out}`);
