/**
 * Seats free in each cabin on a replacement itinerary.
 *
 * One pool per cabin rather than one per option, because 43 hand-written seat
 * lists would be 43 chances for the reseat write to find nothing free and refuse
 * mid-demo. Economy carries rows 6–8 so `forward-cabin` has something to match,
 * both aisle columns so `aisle` does, and row 12 so `exit-row` does — the three
 * preferences beat 4 actually names.
 */
