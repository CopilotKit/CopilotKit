/**
 * The seeded traveler profile behind Aeronova's REST substrate.
 *
 * A `.ts` seed rather than a `.json` one, following this skin's own `seed.ts`
 * (which builds its cabin in code): the option grid below is 43 rows and the
 * helpers keep every row explicit while making a missing or misspelled field a
 * BUILD error rather than a runtime `undefined` on stage.
 *
 * ⚠️ TWO PROPERTIES OF THIS SEED ARE LOAD-BEARING. Read both before editing it.
 *
 * 1. **It agrees with `seed.ts` about Camila's AV1423.** The in-memory concierge
 *    store (`useAirlineData`) is still live and still drives the trip, loyalty
 *    and disruption pages, so both substrates are on screen in the same demo.
 *    Same flight number, route, cities, aircraft, gate, times, `delayed` status
 *    and a 55-minute delay — and AV1423's three rebooking options here are the
 *    same three flights at the same times and prices as `seedRebookingOptions`.
 *    Everything this substrate ADDS sits on records the in-memory store has
 *    never heard of. Do not "improve" either seed's AV1423 without changing the
 *    other.
 *
 * 2. **The board is FAT on purpose.** Beat 3c's own lever set
 *    (`window=evening`, `stops=nonstop`, `sort=price_asc`, `top=5`) leaves TEN
 *    matching rows on `bkg-av1466`, truncated to five. Logistics records why
 *    that matters: a one-row board is indistinguishable from a broken filter on
 *    stage. `rebooking-options.test.ts` asserts the floor directly, so a reseed
 *    that thins the board fails a test instead of a demo.
 *
 * Server-safe: plain TypeScript, no React, no JSX, no `"use client"`.
 */

