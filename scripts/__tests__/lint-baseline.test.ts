import { afterEach, beforeEach, describe, expect, it } from "vitest";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import {
  compareToBaseline,
  countViolations,
  pruneBaseline,
  readBaseline,
  writeBaseline,
} from "../lint/baseline.js";

const ANY = "typescript-eslint(no-explicit-any)";
const SWALLOW = "copilotkit(no-swallowed-error)";
const A = "packages/a/src/a.ts";
const B = "packages/b/src/b.ts";

describe("countViolations", () => {
  it("counts per rule and file, with rules and files sorted", () => {
    const counts = countViolations([
      { rule: ANY, file: B },
      { rule: SWALLOW, file: B },
      { rule: ANY, file: A },
      { rule: ANY, file: B },
    ]);

    expect(counts).toEqual({
      [ANY]: { [A]: 1, [B]: 2 },
      [SWALLOW]: { [B]: 1 },
    });
    expect(Object.keys(counts)).toEqual([SWALLOW, ANY]);
    expect(Object.keys(counts[ANY])).toEqual([A, B]);
  });

  it("returns an empty map when there are no violations", () => {
    expect(countViolations([])).toEqual({});
  });
});

describe("compareToBaseline", () => {
  it("reports a rule the baseline does not have as over", () => {
    const result = compareToBaseline(
      { [SWALLOW]: { [A]: 1 } },
      { [ANY]: { [A]: 1 } },
    );

    expect(result.over).toEqual([
      { rule: SWALLOW, file: A, current: 1, baseline: 0 },
    ]);
  });

  it("reports a file the baseline does not have as over", () => {
    const result = compareToBaseline(
      { [ANY]: { [A]: 1, [B]: 2 } },
      { [ANY]: { [A]: 1 } },
    );

    expect(result).toEqual({
      over: [{ rule: ANY, file: B, current: 2, baseline: 0 }],
      stale: [],
    });
  });

  it("reports a count above the baseline as over", () => {
    const result = compareToBaseline(
      { [ANY]: { [A]: 4 } },
      { [ANY]: { [A]: 3 } },
    );

    expect(result).toEqual({
      over: [{ rule: ANY, file: A, current: 4, baseline: 3 }],
      stale: [],
    });
  });

  it("reports nothing when every count matches", () => {
    const counts = { [ANY]: { [A]: 3, [B]: 1 }, [SWALLOW]: { [A]: 2 } };

    expect(compareToBaseline(counts, counts)).toEqual({ over: [], stale: [] });
  });

  it("reports a lower count and a file with no errors left as stale", () => {
    const result = compareToBaseline(
      { [ANY]: { [A]: 1 } },
      { [ANY]: { [A]: 3, [B]: 2 } },
    );

    expect(result).toEqual({
      over: [],
      stale: [
        { rule: ANY, file: A, current: 1, baseline: 3 },
        { rule: ANY, file: B, current: 0, baseline: 2 },
      ],
    });
  });

  it("only checks the given files and reports no stale pairs", () => {
    const current = { [ANY]: { [A]: 5, [B]: 9 }, [SWALLOW]: { [A]: 1 } };
    const baseline = { [ANY]: { [A]: 2, [B]: 1 }, [SWALLOW]: { [A]: 4 } };

    expect(compareToBaseline(current, baseline, { files: [A] })).toEqual({
      over: [{ rule: ANY, file: A, current: 5, baseline: 2 }],
      stale: [],
    });
  });
});

describe("pruneBaseline", () => {
  it("lowers counts and drops pairs that reach 0", () => {
    const baseline = { [ANY]: { [A]: 3, [B]: 2 }, [SWALLOW]: { [B]: 1 } };

    expect(pruneBaseline({ [ANY]: { [A]: 1 } }, baseline)).toEqual({
      [ANY]: { [A]: 1 },
    });
  });

  it("never raises a count or adds a pair", () => {
    const current = { [ANY]: { [A]: 7, [B]: 1 }, [SWALLOW]: { [A]: 1 } };

    expect(pruneBaseline(current, { [ANY]: { [A]: 2 } })).toEqual({
      [ANY]: { [A]: 2 },
    });
  });
});

describe("readBaseline and writeBaseline", () => {
  let dir: string;

  beforeEach(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), "lint-baseline-"));
  });

  afterEach(() => {
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it("reads a missing file as an empty baseline", () => {
    expect(readBaseline(path.join(dir, "missing.json"))).toEqual({});
  });

  it("writes sorted 2-space JSON that reads back the same", () => {
    const file = path.join(dir, ".lint-baseline", "oxlint.json");
    const comment = "Generated by pnpm lint:baseline. Do not edit by hand.";

    writeBaseline(
      file,
      { [ANY]: { [A]: 3 }, [SWALLOW]: { [B]: 1, [A]: 2 } },
      comment,
    );

    expect(fs.readFileSync(file, "utf8")).toBe(
      [
        "{",
        `  "comment": "${comment}",`,
        '  "rules": {',
        `    "${SWALLOW}": {`,
        `      "${A}": 2,`,
        `      "${B}": 1`,
        "    },",
        `    "${ANY}": {`,
        `      "${A}": 3`,
        "    }",
        "  }",
        "}",
        "",
      ].join("\n"),
    );
    const before = fs.readFileSync(file, "utf8");
    writeBaseline(file, readBaseline(file), comment);
    expect(fs.readFileSync(file, "utf8")).toBe(before);
  });

  it("throws and names the entry when a count is not a positive integer", () => {
    const file = path.join(dir, "bad.json");
    fs.writeFileSync(
      file,
      JSON.stringify({ comment: "", rules: { [ANY]: { [A]: 0 } } }),
    );

    expect(() => readBaseline(file)).toThrow(
      `rules["${ANY}"]["${A}"] must be a positive integer`,
    );
  });
});
