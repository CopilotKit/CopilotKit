#!/usr/bin/env node
/**
 * Fail when documented code teaches a deprecated v1 symbol it did not teach
 * before.
 *
 * WHY A RATCHET AND NOT A BAN. v1 is deprecated but still supported, and we
 * document it on purpose: `reference/v1/**` describes it, `docs/migrate/**`
 * shows the move off it, and the LangGraph and DeepAgents guides teach
 * `@copilotkit/sdk-js/langgraph` because that is the supported path for those
 * frameworks. A blanket "no deprecated import" check reports 184 findings on a
 * clean tree, nearly all of them intentional. Deprecated is not the same as
 * wrong; teaching it somewhere NEW is what goes wrong.
 *
 * That is the real defect this came from. `LangGraphHttpAgent` reached the
 * LangGraph quickstart and then six more pages before anyone noticed (PE-73,
 * PE-108). It was never removed from the package — it still ships from
 * `v1-deprecated-compatibility.ts` — so no compile, type check or export check
 * could have seen it. A page simply acquired a deprecated import, and nothing
 * compared that against the page's previous state.
 *
 * The deprecated set is derived from the packages through
 * `scripts/deprecations/v1-public-api.mjs`, the same TypeScript walk that
 * generates the deprecation notices, so it cannot drift from what is actually
 * marked deprecated. Nothing here is hand-maintained except the baseline, and
 * the baseline is regenerated, never edited by hand.
 *
 * Usage:
 *   node scripts/validate-docs-deprecated-imports.mjs
 *   node scripts/validate-docs-deprecated-imports.mjs --write-baseline
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { getV1PublicApi, repoRoot } from "./deprecations/v1-public-api.mjs";

export const BASELINE_PATH = path.join(
  repoRoot,
  "scripts/docs-deprecated-imports-baseline.json",
);

const CONTENT_ROOT = "showcase/shell-docs/src/content";

/** importPath -> Set of deprecated export names, derived from the packages. */
export function deprecatedSymbolsByImportPath() {
  const { inventories } = getV1PublicApi();
  const map = new Map();
  for (const inventory of inventories) {
    map.set(
      inventory.entrypoint.importPath,
      new Set(inventory.exports.map((e) => e.publicSourceName ?? e.name)),
    );
  }
  return map;
}

// Deliberately a text scan, not a parse. PE-108 established that most
// documented code is not a compilable unit — elided fragments, partial
// snippets, tabs whose sibling declares the same const — so anything that
// needs a working program sees only a minority of what readers are shown.
const IMPORT = /import\s+(?:type\s+)?([^;'"]*?)\s*from\s*["']([^"']+)["']/g;

export function importedNames(clause) {
  const names = [];
  const braced = clause.match(/\{([^}]*)\}/);
  if (braced) {
    for (const part of braced[1].split(",")) {
      const name = part
        .trim()
        .replace(/^type\s+/, "")
        .split(/\s+as\s+/)[0]
        .trim();
      if (name) names.push(name);
    }
  }
  const dflt = clause
    .replace(/\{[^}]*\}/g, "")
    .replace(/^\s*,|,\s*$/g, "")
    .trim();
  if (dflt && /^[A-Za-z_$][\w$]*$/.test(dflt)) names.push(dflt);
  return names;
}

/** Every (file, importPath, symbol) a source teaches, as sorted strings. */
export function findDeprecatedImports(relPath, source, deprecated) {
  const found = new Set();
  IMPORT.lastIndex = 0;
  let match;
  while ((match = IMPORT.exec(source)) !== null) {
    const symbols = deprecated.get(match[2]);
    if (!symbols) continue;
    for (const name of importedNames(match[1])) {
      if (symbols.has(name)) found.add(`${relPath}\t${match[2]}\t${name}`);
    }
  }
  return [...found];
}

function contentFiles() {
  return execFileSync("git", ["ls-files", "--", CONTENT_ROOT], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  })
    .split("\n")
    .filter((f) => f.endsWith(".mdx"));
}

export function scanRepo() {
  const deprecated = deprecatedSymbolsByImportPath();
  const found = [];
  for (const rel of contentFiles()) {
    const abs = path.join(repoRoot, rel);
    if (!existsSync(abs)) continue;
    found.push(
      ...findDeprecatedImports(rel, readFileSync(abs, "utf8"), deprecated),
    );
  }
  return found.sort();
}

export function readBaseline() {
  if (!existsSync(BASELINE_PATH)) return [];
  return JSON.parse(readFileSync(BASELINE_PATH, "utf8")).entries ?? [];
}

function main() {
  const write = process.argv.includes("--write-baseline");
  const current = scanRepo();

  if (write) {
    writeFileSync(
      BASELINE_PATH,
      `${JSON.stringify(
        {
          comment:
            "Generated by scripts/validate-docs-deprecated-imports.mjs --write-baseline. Do not edit by hand. Entries are file\\timportPath\\tsymbol. This list should only shrink.",
          entries: current,
        },
        null,
        2,
      )}\n`,
    );
    console.log(
      `wrote ${current.length} entries to ${path.relative(repoRoot, BASELINE_PATH)}`,
    );
    return;
  }

  const baseline = new Set(readBaseline());
  const added = current.filter((e) => !baseline.has(e));
  const removed = [...baseline].filter((e) => !current.includes(e)).sort();

  if (added.length > 0) {
    console.error(
      `\n${added.length} documented import(s) newly teach a deprecated v1 symbol:\n`,
    );
    for (const entry of added) {
      const [file, importPath, symbol] = entry.split("\t");
      console.error(`  ${file}\n      ${symbol}  from  ${importPath}`);
    }
    console.error(
      "\nv1 is still supported, so this is not automatically wrong — but a page\n" +
        "that did not teach it before now does. Either point the example at the v2\n" +
        "surface, or, if teaching v1 here is deliberate, re-run with\n" +
        "--write-baseline and say why in the commit message.\n",
    );
    process.exitCode = 1;
    return;
  }

  if (removed.length > 0) {
    console.error(
      `\n${removed.length} baseline entr(ies) no longer exist. The list only shrinks when\n` +
        "it is regenerated, so re-run with --write-baseline to record the fix:\n",
    );
    for (const entry of removed)
      console.error(`  ${entry.split("\t").join("  ")}`);
    console.error("");
    process.exitCode = 1;
    return;
  }

  console.log(
    `docs deprecated-import baseline holds: ${current.length} known, 0 new.`,
  );
}

if (import.meta.url === `file://${process.argv[1]}`) main();
